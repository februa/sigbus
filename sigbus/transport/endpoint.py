from typing import Protocol


class ReservableEndpoint(Protocol):
    """Optional transport helpers used by Node, separate from ordinary leases.

    reserve atomically pins an available resource or raises BlockingIOError.
    Its result supports check/checkout/commit/release and deferred send/discard.
    Cancelling a read reservation must not consume it unless consume=True.
    """
    def check_idle(self) -> None: ...
    def reserve(self, timestamp=None, *, batch=False): ...
    def queue_pending(self): ...
    def discard_pending(self) -> None: ...

class WriteEndpoint(Protocol):
    def write_request(self): ...
    def ack(self) -> None: ...
    def has_pending(self) -> bool: ...
    def flush(self) -> None: ...

    def acquire(self, timestamp: int):
        ...

    def close(self) -> None:
        ...

class ReadEndpoint(Protocol):
    def ack(self) -> None: ...
    def has_frame(self) -> bool:
        ...

    def acquire_batch(self):
        ...

    def acquire(self):
        ...

    def close(self) -> None:
        ...
